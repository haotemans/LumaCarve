"""Triton CUDA forward: simultaneously apply Cosmos half-split RoPE to Q and K.

Diffusers Cosmos RoPE uses use_real_unbind_dim=-2:
rotated = concat(-x[..., D//2:], x[..., :D//2]).
The frequency table already has shape [tokens, head_dim] (with duplicated
half-frequencies); it is generated by the original Diffusers RoPE module.

No autotune and no CUDA profiling are performed. Import only on first call.
"""
from __future__ import annotations

import triton
import triton.language as tl


@triton.jit
def _fused_qk_rope(
    q_ptr, k_ptr, cos_ptr, sin_ptr, q_out_ptr, k_out_ptr,
    total_rows, seq_len, n_heads,
    q_stride_b, q_stride_h, q_stride_s, q_stride_d,
    k_stride_b, k_stride_h, k_stride_s, k_stride_d,
    cos_stride_s, cos_stride_d,
    sin_stride_s, sin_stride_d,
    dim: tl.constexpr,
    row_block: tl.constexpr,
    col_block: tl.constexpr,
):
    rows = tl.program_id(0) * row_block + tl.arange(0, row_block)
    cols = tl.arange(0, col_block)
    active = (rows[:, None] < total_rows) & (cols[None, :] < dim)

    batch = rows // (n_heads * seq_len)
    head = (rows // seq_len) % n_heads
    pos = rows % seq_len

    q_base = batch * q_stride_b + head * q_stride_h + pos * q_stride_s
    k_base = batch * k_stride_b + head * k_stride_h + pos * k_stride_s
    second_half = cols >= (dim // 2)
    rotated_cols = tl.where(second_half, cols - dim // 2, cols + dim // 2)
    sign = tl.where(second_half, 1.0, -1.0)

    q = tl.load(q_ptr + q_base[:, None] + cols[None, :] * q_stride_d, active, 0).to(tl.float32)
    qr = tl.load(q_ptr + q_base[:, None] + rotated_cols[None, :] * q_stride_d, active, 0).to(tl.float32)
    k = tl.load(k_ptr + k_base[:, None] + cols[None, :] * k_stride_d, active, 0).to(tl.float32)
    kr = tl.load(k_ptr + k_base[:, None] + rotated_cols[None, :] * k_stride_d, active, 0).to(tl.float32)

    cos = tl.load(cos_ptr + pos[:, None] * cos_stride_s + cols[None, :] * cos_stride_d, active, 0).to(tl.float32)
    sin = tl.load(sin_ptr + pos[:, None] * sin_stride_s + cols[None, :] * sin_stride_d, active, 0).to(tl.float32)

    qo = q * cos + (qr * sign[None, :]) * sin
    ko = k * cos + (kr * sign[None, :]) * sin
    out_offset = rows[:, None] * dim + cols[None, :]
    tl.store(q_out_ptr + out_offset, qo, active)
    tl.store(k_out_ptr + out_offset, ko, active)


def launch(q, k, cos, sin):
    """Q/K shape [B,H,S,D], cosine/sine shape [S,D]. No autotune."""
    import torch

    batch, heads, seq_len, dim = q.shape
    q_out = torch.empty((batch, heads, seq_len, dim), dtype=q.dtype, device=q.device)
    k_out = torch.empty((batch, heads, seq_len, dim), dtype=k.dtype, device=k.device)
    row_block = 4
    col_block = triton.next_power_of_2(dim)
    _fused_qk_rope[(triton.cdiv(batch * heads * seq_len, row_block),)](
        q, k, cos, sin, q_out, k_out,
        batch * heads * seq_len, seq_len, heads,
        *q.stride(), *k.stride(),
        *cos.stride(), *sin.stride(),
        dim, row_block, col_block,
        num_warps=4,
        enable_fp_fusion=False,
    )
    return q_out, k_out
